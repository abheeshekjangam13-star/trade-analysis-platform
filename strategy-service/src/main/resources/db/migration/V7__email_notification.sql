-- Outbox of emails to users and admins (sign-up received, approved, rejected). Rows are written in the same
-- transaction as the user change, then sent by EmailDispatcher; failures are retried a few times.
CREATE TABLE email_notification (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT REFERENCES app_user (id) ON DELETE SET NULL,
    recipient   VARCHAR(255)                NOT NULL,
    kind        VARCHAR(40)                 NOT NULL,
    subject     VARCHAR(255)                NOT NULL,
    body        TEXT                        NOT NULL,
    status      VARCHAR(12)                 NOT NULL,
    attempts    INT                         NOT NULL,
    last_error  VARCHAR(1000),
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    sent_at     TIMESTAMP(6) WITH TIME ZONE
);
CREATE INDEX ix_email_notification_status ON email_notification (status, created_at);
CREATE INDEX ix_email_notification_user ON email_notification (user_id, created_at);
