-- Strategy service core tables (same shape as the earlier H2 tables, so existing data copies 1:1).

CREATE TABLE strategy (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255)                NOT NULL,
    description TEXT,
    type        VARCHAR(255)                NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_strategy_name UNIQUE (name)
);

CREATE TABLE strategy_param (
    strategy_id BIGINT       NOT NULL REFERENCES strategy (id) ON DELETE CASCADE,
    param_key   VARCHAR(255) NOT NULL,
    param_value VARCHAR(255),
    PRIMARY KEY (strategy_id, param_key)
);

CREATE TABLE backtest_result (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    strategy_id     BIGINT REFERENCES strategy (id),
    symbol          VARCHAR(255),
    from_date       TIMESTAMP(6) WITH TIME ZONE,
    to_date         TIMESTAMP(6) WITH TIME ZONE,
    initial_capital DOUBLE PRECISION NOT NULL,
    final_capital   DOUBLE PRECISION NOT NULL,
    total_return    DOUBLE PRECISION NOT NULL,
    max_drawdown    DOUBLE PRECISION NOT NULL,
    total_trades    INTEGER          NOT NULL,
    winning_trades  INTEGER          NOT NULL,
    sharpe_ratio    DOUBLE PRECISION NOT NULL
);
CREATE INDEX idx_backtest_result_strategy ON backtest_result (strategy_id);

CREATE TABLE nifty_trade_log (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    backtest_result_id  BIGINT,
    strategy_id         BIGINT,
    symbol              VARCHAR(255),
    trade_date          DATE,
    trade_number        INTEGER          NOT NULL,
    breakout_type       VARCHAR(255),
    reference_high      DOUBLE PRECISION NOT NULL,
    reference_low       DOUBLE PRECISION NOT NULL,
    reference_timestamp TIMESTAMP(6) WITH TIME ZONE,
    entry_timestamp     TIMESTAMP(6) WITH TIME ZONE,
    entry_spot_price    DOUBLE PRECISION NOT NULL,
    option_type         VARCHAR(255),
    strike_price        INTEGER          NOT NULL,
    lots                INTEGER          NOT NULL,
    lot_size            INTEGER          NOT NULL,
    initial_stop_loss   DOUBLE PRECISION,
    final_stop_loss     DOUBLE PRECISION,
    gap_percent         DOUBLE PRECISION,
    charges             DOUBLE PRECISION,
    exit_timestamp      TIMESTAMP(6) WITH TIME ZONE,
    exit_spot_price     DOUBLE PRECISION NOT NULL,
    exit_reason         VARCHAR(255),
    estimated_pnl       DOUBLE PRECISION NOT NULL,
    created_at          TIMESTAMP(6) WITH TIME ZONE
);
CREATE INDEX idx_nifty_trade_log_backtest ON nifty_trade_log (backtest_result_id);
CREATE INDEX idx_nifty_trade_log_strategy ON nifty_trade_log (strategy_id);
CREATE INDEX idx_nifty_trade_log_date     ON nifty_trade_log (trade_date);

CREATE TABLE nifty_position_state (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version               BIGINT           NOT NULL,
    strategy_id           BIGINT,
    trade_date            DATE,
    daily_trade_count     INTEGER          NOT NULL,
    direction             VARCHAR(255),
    trading_symbol        VARCHAR(255),
    quantity              INTEGER          NOT NULL,
    reference_high        DOUBLE PRECISION NOT NULL,
    reference_low         DOUBLE PRECISION NOT NULL,
    initial_stop_loss     DOUBLE PRECISION NOT NULL,
    current_stop_loss     DOUBLE PRECISION NOT NULL,
    last_processed_candle TIMESTAMP(6) WITH TIME ZONE,
    entry_order_id        VARCHAR(255),
    entry_order_status    VARCHAR(255),
    exit_order_id         VARCHAR(255),
    exit_order_status     VARCHAR(255),
    exit_order_quantity   INTEGER          NOT NULL,
    exit_filled_quantity  INTEGER          NOT NULL,
    status                VARCHAR(255),
    updated_at            TIMESTAMP(6) WITH TIME ZONE
);
CREATE INDEX idx_nifty_position_state_strategy ON nifty_position_state (strategy_id, status);
