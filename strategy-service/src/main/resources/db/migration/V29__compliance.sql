-- Readiness for broker sponsorship and NSE algo-provider empanelment (SEBI retail algo framework).

-- Exchange-issued Algo IDs. scope = DEFAULT, MANUAL (manual order tickets) or a strategy type
-- (e.g. NIFTY_OPENING_BREAKOUT). Live orders carry the Algo ID of their strategy type, else DEFAULT.
CREATE TABLE algo_id (
    scope      VARCHAR(64)                 PRIMARY KEY,
    algo_id    VARCHAR(32)                 NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_by BIGINT
);

-- Compliance switches (one row). All off by default, so turning them on is an admin decision.
CREATE TABLE compliance_control (
    id                    SMALLINT DEFAULT 1 PRIMARY KEY,
    algo_id_required      BOOLEAN DEFAULT FALSE NOT NULL,   -- refuse new live entries without an Algo ID
    live_needs_two_factor BOOLEAN DEFAULT FALSE NOT NULL,   -- live trading needs two-factor sign-in turned on
    live_needs_pan        BOOLEAN DEFAULT FALSE NOT NULL,   -- live trading needs a PAN an admin verified
    grievance_name        VARCHAR(120),
    grievance_email       VARCHAR(200),
    grievance_phone       VARCHAR(40),
    updated_at            TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_compliance_control_single_row CHECK (id = 1)
);
INSERT INTO compliance_control (id, updated_at) VALUES (1, CURRENT_TIMESTAMP);

-- Every order keeps the Algo ID it was sent with and the strategy's type, name and settings at that moment.
ALTER TABLE trade_order ADD COLUMN algo_id VARCHAR(32);
ALTER TABLE trade_order ADD COLUMN strategy_snapshot VARCHAR(4000);

-- Who changed what (controls, Algo IDs, live access, LIVE switches, two-factor, PAN). Never deleted.
CREATE TABLE compliance_audit (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    user_id    BIGINT,
    username   VARCHAR(64),
    action     VARCHAR(64)                 NOT NULL,
    details    VARCHAR(2000)
);
CREATE INDEX idx_compliance_audit_created ON compliance_audit (created_at);

-- Acceptance of the live trading risk disclosure, per version.
CREATE TABLE risk_acceptance (
    user_id     BIGINT                      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    version     VARCHAR(16)                 NOT NULL,
    accepted_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (user_id, version)
);

-- Two-factor sign-in with an authenticator app (TOTP, RFC 6238). The secret is encrypted like broker secrets.
CREATE TABLE user_totp (
    user_id    BIGINT PRIMARY KEY REFERENCES app_user (id) ON DELETE CASCADE,
    secret_enc VARCHAR(512)                NOT NULL,
    enabled    BOOLEAN DEFAULT FALSE       NOT NULL,
    last_step  BIGINT,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    enabled_at TIMESTAMP(6) WITH TIME ZONE
);

-- Each user's PAN, linked to their client ID. Stored encrypted; pan_hash (keyed HMAC) keeps one PAN to one account.
CREATE TABLE user_pan (
    user_id     BIGINT PRIMARY KEY REFERENCES app_user (id) ON DELETE CASCADE,
    pan_enc     VARCHAR(512)                NOT NULL,
    pan_hash    VARCHAR(64)                 NOT NULL,
    pan_masked  VARCHAR(10)                 NOT NULL,
    name_on_pan VARCHAR(120),
    verified    BOOLEAN DEFAULT FALSE       NOT NULL,
    verified_at TIMESTAMP(6) WITH TIME ZONE,
    verified_by BIGINT,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE UNIQUE INDEX ux_user_pan_hash ON user_pan (pan_hash);
