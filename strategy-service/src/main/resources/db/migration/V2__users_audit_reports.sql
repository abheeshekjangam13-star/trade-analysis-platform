-- Report: one row per trading day of a backtest (traded or not, and why not).
CREATE TABLE backtest_daily_report (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    backtest_result_id BIGINT           NOT NULL REFERENCES backtest_result (id) ON DELETE CASCADE,
    trade_date         DATE             NOT NULL,
    day_of_week        VARCHAR(3)       NOT NULL,
    gap_percent        DOUBLE PRECISION,
    status             VARCHAR(16)      NOT NULL,   -- TRADED / NO_TRADE / SKIPPED / NO_DATA
    reason             VARCHAR(255),
    trades             INTEGER          NOT NULL,
    net_pnl            DOUBLE PRECISION NOT NULL,
    CONSTRAINT uk_backtest_daily UNIQUE (backtest_result_id, trade_date)
);

-- Report: one row per calendar month of a backtest.
CREATE TABLE backtest_monthly_stat (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    backtest_result_id    BIGINT           NOT NULL REFERENCES backtest_result (id) ON DELETE CASCADE,
    period_month          VARCHAR(7)       NOT NULL,   -- yyyy-MM
    trades                INTEGER          NOT NULL,
    wins                  INTEGER          NOT NULL,
    losses                INTEGER          NOT NULL,
    gross_pnl             DOUBLE PRECISION NOT NULL,
    charges               DOUBLE PRECISION NOT NULL,
    net_pnl               DOUBLE PRECISION NOT NULL,
    avg_win               DOUBLE PRECISION NOT NULL,
    avg_loss              DOUBLE PRECISION NOT NULL,
    best_trade            DOUBLE PRECISION NOT NULL,
    worst_trade           DOUBLE PRECISION NOT NULL,
    target_hits           INTEGER          NOT NULL,
    stop_exits            INTEGER          NOT NULL,
    failed_breakout_exits INTEGER          NOT NULL,
    eod_exits             INTEGER          NOT NULL,
    max_drawdown          DOUBLE PRECISION NOT NULL,   -- rupees, within the month
    cumulative_pnl        DOUBLE PRECISION NOT NULL,   -- running total since the backtest start
    CONSTRAINT uk_backtest_monthly UNIQUE (backtest_result_id, period_month)
);

-- Portfolios: named groups of strategies reported together (e.g. CE 56 + PE 55).
CREATE TABLE portfolio (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(255)                NOT NULL,
    description        TEXT,
    created_by_user_id BIGINT REFERENCES app_user (id),
    created_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_portfolio_name UNIQUE (name)
);

CREATE TABLE portfolio_strategy (
    portfolio_id BIGINT NOT NULL REFERENCES portfolio (id) ON DELETE CASCADE,
    strategy_id  BIGINT NOT NULL REFERENCES strategy (id),
    PRIMARY KEY (portfolio_id, strategy_id)
);

-- Report: combined result of a portfolio over one look-back window.
CREATE TABLE portfolio_report (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id   BIGINT                      NOT NULL REFERENCES portfolio (id) ON DELETE CASCADE,
    window_days    INTEGER                     NOT NULL,
    symbol         VARCHAR(32)                 NOT NULL,
    from_date      DATE                        NOT NULL,
    to_date        DATE                        NOT NULL,
    capital        DOUBLE PRECISION            NOT NULL,
    trades         INTEGER                     NOT NULL,
    wins           INTEGER                     NOT NULL,
    gross_pnl      DOUBLE PRECISION            NOT NULL,
    charges        DOUBLE PRECISION            NOT NULL,
    net_pnl        DOUBLE PRECISION            NOT NULL,
    end_capital    DOUBLE PRECISION            NOT NULL,
    return_pct     DOUBLE PRECISION            NOT NULL,
    profit_factor  DOUBLE PRECISION,                         -- null when there are no losing trades
    max_drawdown   DOUBLE PRECISION            NOT NULL,     -- rupees
    run_by_user_id BIGINT REFERENCES app_user (id),
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_portfolio_report_portfolio ON portfolio_report (portfolio_id, created_at);

CREATE TABLE portfolio_report_item (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_report_id BIGINT           NOT NULL REFERENCES portfolio_report (id) ON DELETE CASCADE,
    strategy_id         BIGINT           NOT NULL REFERENCES strategy (id),
    backtest_result_id  BIGINT           NOT NULL REFERENCES backtest_result (id),
    trades              INTEGER          NOT NULL,
    wins                INTEGER          NOT NULL,
    net_pnl             DOUBLE PRECISION NOT NULL,
    max_drawdown        DOUBLE PRECISION NOT NULL
);
