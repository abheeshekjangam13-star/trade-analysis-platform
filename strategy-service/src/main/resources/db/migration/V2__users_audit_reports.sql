-- Users, roles and access audit (login is added later; until then users are identified by the X-User header).

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64)                 NOT NULL,
    email         VARCHAR(255),
    full_name     VARCHAR(255),
    password_hash VARCHAR(255),                         -- filled once login exists
    status        VARCHAR(20)                 NOT NULL, -- ACTIVE / DISABLED
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    last_seen_at  TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_app_user_username UNIQUE (username),
    CONSTRAINT uk_app_user_email    UNIQUE (email)
);

CREATE TABLE app_role (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(32)  NOT NULL,
    description VARCHAR(255),
    CONSTRAINT uk_app_role_name UNIQUE (name)
);

CREATE TABLE app_user_role (
    user_id BIGINT NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    role_id BIGINT NOT NULL REFERENCES app_role (id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, role_id)
);

