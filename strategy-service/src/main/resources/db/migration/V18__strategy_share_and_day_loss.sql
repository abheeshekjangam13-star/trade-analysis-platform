-- An admin shares a strategy with chosen users. The user sees it as an invitation; accepting it creates the user's
-- own copy (created_strategy_id), declining it leaves nothing behind.
CREATE TABLE strategy_share (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    strategy_id         BIGINT                      NOT NULL REFERENCES strategy (id),
    shared_by_user_id   BIGINT                      NOT NULL REFERENCES app_user (id),
    shared_with_user_id BIGINT                      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    status              VARCHAR(20)                 NOT NULL,
    note                VARCHAR(500),
    created_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    responded_at        TIMESTAMP(6) WITH TIME ZONE,
    created_strategy_id BIGINT REFERENCES strategy (id) ON DELETE SET NULL
);
CREATE INDEX idx_strategy_share_with ON strategy_share (shared_with_user_id, status);
CREATE INDEX idx_strategy_share_strategy ON strategy_share (strategy_id);

-- Each user's own maximum loss for a day across all their strategies (per mode: paper and live counted apart).
-- Null = not set yet; users must set it before switching a strategy to paper or live.
ALTER TABLE app_user ADD COLUMN max_day_loss DOUBLE PRECISION;
