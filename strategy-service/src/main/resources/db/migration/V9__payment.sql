-- Razorpay one-time payments for a month of GOLD or PREMIUM. A verified payment (Checkout signature or webhook)
-- activates the plan; razorpay_order_id is unique so each order activates at most once.
CREATE TABLE payment_order (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT                      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    plan                VARCHAR(20)                 NOT NULL,
    days                INT                         NOT NULL,
    amount_paise        BIGINT                      NOT NULL,
    currency            VARCHAR(3)                  NOT NULL,
    razorpay_order_id   VARCHAR(64)                 NOT NULL,
    razorpay_payment_id VARCHAR(64),
    status              VARCHAR(12)                 NOT NULL,
    failure_reason      VARCHAR(500),
    created_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    paid_at             TIMESTAMP(6) WITH TIME ZONE,
    plan_valid_until    TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_payment_order_rzp UNIQUE (razorpay_order_id)
);
CREATE INDEX ix_payment_order_user ON payment_order (user_id, created_at);
