-- Simulated backtest days, so running a backtest again only simulates the days it hasn't seen (see BacktestDayCache).
-- One row per strategy fingerprint (strategy, its exact parameters, index, engine version) and past trading day:
-- the day's report, its trades before the capital limit, and its signals, as JSON. Rebuildable at any time: deleting
-- rows only makes the next run simulate those days again.
CREATE TABLE backtest_day_cache (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cache_key    VARCHAR(64)                 NOT NULL,
    trade_date   DATE                        NOT NULL,
    payload      TEXT                        NOT NULL,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    last_used_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_backtest_day_cache UNIQUE (cache_key, trade_date)
);
CREATE INDEX idx_backtest_day_cache_used ON backtest_day_cache (last_used_at);
