-- Live order billing: every live-trading plan includes live orders (credited when the plan starts or renews); after
-- those, each live entry costs a fixed price from prepaid credits bought with Razorpay. Exits are never charged.
ALTER TABLE app_user ADD COLUMN live_orders_left INTEGER NOT NULL DEFAULT 0;      -- included live orders still unused
ALTER TABLE app_user ADD COLUMN live_orders_granted INTEGER NOT NULL DEFAULT 0;   -- size of the latest allowance (for the 70% notice)
ALTER TABLE app_user ADD COLUMN live_orders_warned BOOLEAN NOT NULL DEFAULT FALSE; -- the "70% used" notice was sent for it
ALTER TABLE app_user ADD COLUMN credit_paise BIGINT NOT NULL DEFAULT 0;           -- prepaid credits

-- A payment buys either a plan (PLAN) or credits (CREDITS, no plan).
ALTER TABLE payment_order ADD COLUMN kind VARCHAR(12) DEFAULT 'PLAN' NOT NULL;
ALTER TABLE payment_order ALTER COLUMN plan DROP NOT NULL;

-- Every movement: GRANT (included orders credited), INCLUDED (an order used one), CREDITS (an order paid from credits,
-- negative), REFUND (an order Kite rejected later, given back), TOPUP (credits bought), ADJUST (by an admin).
CREATE TABLE live_order_charge (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    trade_order_id BIGINT,
    source         VARCHAR(10)  NOT NULL,
    orders         INTEGER      NOT NULL,   -- change in included orders (+ granted, − used)
    amount_paise   BIGINT       NOT NULL,   -- change in credits (+ bought, − spent)
    note           VARCHAR(200),
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_live_order_charge_user ON live_order_charge (user_id, created_at);
CREATE INDEX ix_live_order_charge_order ON live_order_charge (trade_order_id);
