-- Phone alerts (Web Push): one row per browser/phone a user turned alerts on in. The endpoint is the push service URL
-- (FCM for Android Chrome); p256dh and auth are the browser's keys the payload is encrypted with.
CREATE TABLE push_subscription (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT                      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    endpoint     VARCHAR(1000)               NOT NULL UNIQUE,
    p256dh       VARCHAR(200)                NOT NULL,
    auth         VARCHAR(100)                NOT NULL,
    user_agent   VARCHAR(300),
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    last_sent_at TIMESTAMP(6) WITH TIME ZONE,
    failures     INT                         DEFAULT 0 NOT NULL
);
CREATE INDEX ix_push_subscription_user ON push_subscription (user_id);

-- The server's VAPID key pair, created once when PUSH_VAPID_PUBLIC_KEY / PUSH_VAPID_PRIVATE_KEY are not set.
-- The private key is encrypted like the Kite secrets (KITE_ENCRYPTION_KEY).
CREATE TABLE push_vapid_key (
    id              INT PRIMARY KEY,
    public_key      VARCHAR(200)                NOT NULL,
    private_key_enc VARCHAR(500)                NOT NULL,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
