-- Trading: every order the platform sends (paper or live), global controls, per-strategy live mode and the
-- positions the live runner opens for strategies.

CREATE TABLE trading_control (
    id                     SMALLINT DEFAULT 1 PRIMARY KEY,
    kill_switch            BOOLEAN          NOT NULL,
    max_orders_per_day     INTEGER          NOT NULL,
    max_quantity_per_order INTEGER          NOT NULL,
    daily_loss_limit       DOUBLE PRECISION NOT NULL,   -- rupees; new entries stop once today's realized loss reaches it
    updated_by_user_id     BIGINT REFERENCES app_user (id),
    updated_at             TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_trading_control_single_row CHECK (id = 1)
);
INSERT INTO trading_control (id, kill_switch, max_orders_per_day, max_quantity_per_order, daily_loss_limit, updated_at)
VALUES (1, FALSE, 10, 130, 5000, CURRENT_TIMESTAMP);

CREATE TABLE strategy_live_config (
    strategy_id        BIGINT PRIMARY KEY REFERENCES strategy (id) ON DELETE CASCADE,
    mode               VARCHAR(8)  NOT NULL,   -- OFF / PAPER / LIVE
    product            VARCHAR(8)  NOT NULL,   -- MIS / NRML
    updated_by_user_id BIGINT REFERENCES app_user (id),
    updated_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE trade_order (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trade_date       DATE                        NOT NULL,
    mode             VARCHAR(8)                  NOT NULL,   -- PAPER / LIVE
    source           VARCHAR(16)                 NOT NULL,   -- MANUAL / STRATEGY / KILL_SWITCH
    strategy_id      BIGINT,
    exchange         VARCHAR(8)                  NOT NULL,
    tradingsymbol    VARCHAR(64)                 NOT NULL,
    transaction_type VARCHAR(4)                  NOT NULL,   -- BUY / SELL
    quantity         INTEGER                     NOT NULL,
    product          VARCHAR(8)                  NOT NULL,
    order_type       VARCHAR(8)                  NOT NULL,   -- MARKET / LIMIT / SL / SL-M
    price            DOUBLE PRECISION,
    trigger_price    DOUBLE PRECISION,
    status           VARCHAR(16)                 NOT NULL,   -- OPEN / COMPLETE / REJECTED / CANCELLED
    broker_order_id  VARCHAR(64),
    filled_quantity  INTEGER                     NOT NULL,
    average_price    DOUBLE PRECISION,
    message          VARCHAR(512),
    user_id          BIGINT REFERENCES app_user (id),
    created_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_trade_order_date   ON trade_order (trade_date, mode);
CREATE INDEX idx_trade_order_broker ON trade_order (broker_order_id);

CREATE TABLE live_position (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    strategy_id    BIGINT                      NOT NULL REFERENCES strategy (id),
    trade_date     DATE                        NOT NULL,
    mode           VARCHAR(8)                  NOT NULL,
    option_type    VARCHAR(2)                  NOT NULL,
    tradingsymbol  VARCHAR(64),
    quantity       INTEGER                     NOT NULL,
    entry_candle   TIMESTAMP(6) WITH TIME ZONE NOT NULL,   -- 5-min breakout candle the engine entered on
    entry_spot     DOUBLE PRECISION            NOT NULL,
    current_stop   DOUBLE PRECISION,
    entry_order_id BIGINT REFERENCES trade_order (id),
    entry_price    DOUBLE PRECISION,
    exit_order_id  BIGINT REFERENCES trade_order (id),
    exit_price     DOUBLE PRECISION,
    exit_spot      DOUBLE PRECISION,
    exit_reason    VARCHAR(32),
    status         VARCHAR(12)                 NOT NULL,   -- OPEN / CLOSED / FAILED
    pnl            DOUBLE PRECISION,
    message        VARCHAR(512),
    opened_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    closed_at      TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_live_position_entry UNIQUE (strategy_id, mode, entry_candle)
);
CREATE INDEX idx_live_position_day ON live_position (trade_date, status);
