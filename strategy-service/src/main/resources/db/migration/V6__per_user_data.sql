-- Each user's data is private (admins see everything). Rows from before users existed belong to the first admin.
-- Trading becomes per user: every user has their own OFF/PAPER/LIVE setting per strategy, and their own positions.

CREATE TABLE strategy_user_mode (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    strategy_id BIGINT                      NOT NULL REFERENCES strategy (id) ON DELETE CASCADE,
    user_id     BIGINT                      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    mode        VARCHAR(8)                  NOT NULL,
    product     VARCHAR(8)                  NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_strategy_user_mode UNIQUE (strategy_id, user_id)
);

INSERT INTO strategy_user_mode (strategy_id, user_id, mode, product, updated_at)
SELECT c.strategy_id,
       COALESCE(c.updated_by_user_id, (SELECT MIN(ur.user_id) FROM app_user_role ur JOIN app_role r ON r.id = ur.role_id WHERE r.name = 'ADMIN')),
       c.mode, c.product, c.updated_at
FROM strategy_live_config c
WHERE COALESCE(c.updated_by_user_id, (SELECT MIN(ur.user_id) FROM app_user_role ur JOIN app_role r ON r.id = ur.role_id WHERE r.name = 'ADMIN')) IS NOT NULL;

DROP TABLE strategy_live_config;

ALTER TABLE live_position ADD COLUMN user_id BIGINT REFERENCES app_user (id);
ALTER TABLE live_position DROP CONSTRAINT uk_live_position_entry;
ALTER TABLE live_position ADD CONSTRAINT uk_live_position_user_entry UNIQUE (strategy_id, user_id, mode, entry_candle);
CREATE INDEX ix_live_position_user ON live_position (user_id, trade_date);
CREATE INDEX ix_trade_order_user ON trade_order (user_id, trade_date);
CREATE INDEX ix_strategy_owner ON strategy (created_by_user_id);
CREATE INDEX ix_backtest_owner ON backtest_result (run_by_user_id);
CREATE INDEX ix_portfolio_owner ON portfolio (created_by_user_id);

-- Old rows without an owner go to the first admin (if there is one yet; otherwise only admins see them).
UPDATE live_position SET user_id = (SELECT MIN(ur.user_id) FROM app_user_role ur JOIN app_role r ON r.id = ur.role_id WHERE r.name = 'ADMIN') WHERE user_id IS NULL;
UPDATE trade_order SET user_id = (SELECT MIN(ur.user_id) FROM app_user_role ur JOIN app_role r ON r.id = ur.role_id WHERE r.name = 'ADMIN') WHERE user_id IS NULL;
UPDATE strategy SET created_by_user_id = (SELECT MIN(ur.user_id) FROM app_user_role ur JOIN app_role r ON r.id = ur.role_id WHERE r.name = 'ADMIN') WHERE created_by_user_id IS NULL;
UPDATE backtest_result SET run_by_user_id = (SELECT MIN(ur.user_id) FROM app_user_role ur JOIN app_role r ON r.id = ur.role_id WHERE r.name = 'ADMIN') WHERE run_by_user_id IS NULL;
UPDATE portfolio SET created_by_user_id = (SELECT MIN(ur.user_id) FROM app_user_role ur JOIN app_role r ON r.id = ur.role_id WHERE r.name = 'ADMIN') WHERE created_by_user_id IS NULL;
UPDATE portfolio_report SET run_by_user_id = (SELECT MIN(ur.user_id) FROM app_user_role ur JOIN app_role r ON r.id = ur.role_id WHERE r.name = 'ADMIN') WHERE run_by_user_id IS NULL;

-- Names only need to be unique per owner (another user's names must not be revealed or block yours).
ALTER TABLE strategy DROP CONSTRAINT uk_strategy_name;
ALTER TABLE strategy ADD CONSTRAINT uk_strategy_owner_name UNIQUE (created_by_user_id, name);
ALTER TABLE portfolio DROP CONSTRAINT uk_portfolio_name;
ALTER TABLE portfolio ADD CONSTRAINT uk_portfolio_owner_name UNIQUE (created_by_user_id, name);
