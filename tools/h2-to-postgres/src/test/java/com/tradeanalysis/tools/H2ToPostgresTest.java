package com.tradeanalysis.tools;

import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.Statement;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

class H2ToPostgresTest {

    @Test
    void copiesMatchingColumnsKeepingIdsAndRefusesANonEmptyTarget() throws Exception {
        try (Connection src = DriverManager.getConnection("jdbc:h2:mem:src" + System.nanoTime());
             Connection dst = DriverManager.getConnection("jdbc:h2:mem:dst" + System.nanoTime() + ";MODE=PostgreSQL")) {
            try (Statement s = src.createStatement()) {   // shape Hibernate created in the old H2 files
                s.execute("CREATE TABLE NIFTY_POSITION_STATE (ID BIGINT PRIMARY KEY, STATUS ENUM('OPEN','CLOSED'), "
                        + "UPDATED_AT TIMESTAMP(6) WITH TIME ZONE, OLD_COLUMN INT)");
                s.execute("INSERT INTO NIFTY_POSITION_STATE VALUES (7, 'OPEN', TIMESTAMP WITH TIME ZONE '2026-11-04 09:30:00+05:30', 1)");
                s.execute("INSERT INTO NIFTY_POSITION_STATE VALUES (9, 'CLOSED', NULL, 2)");
            }
            try (Statement s = dst.createStatement()) {
                s.execute("CREATE TABLE nifty_position_state (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                        + "status VARCHAR(255), updated_at TIMESTAMP(6) WITH TIME ZONE, new_column INT)");
            }

            assertThat(H2ToPostgres.copyTable(src, dst, "nifty_position_state")).isEqualTo(2);

            try (Statement s = dst.createStatement();
                 ResultSet rs = s.executeQuery("SELECT id, status, updated_at, new_column FROM nifty_position_state ORDER BY id")) {
                assertThat(rs.next()).isTrue();
                assertThat(rs.getLong(1)).isEqualTo(7);
                assertThat(rs.getString(2)).isEqualTo("OPEN");
                assertThat(rs.getObject(3, java.time.OffsetDateTime.class).toInstant())
                        .isEqualTo(java.time.Instant.parse("2026-11-04T04:00:00Z"));
                assertThat(rs.getObject(4)).isNull();
                assertThat(rs.next()).isTrue();
                assertThat(rs.getLong(1)).isEqualTo(9);
            }

            assertThatThrownBy(() -> H2ToPostgres.copyTable(src, dst, "nifty_position_state"))
                    .hasMessageContaining("already has rows");
        }
    }

    @Test
    void missingSourceTableIsSkipped() throws Exception {
        try (Connection src = DriverManager.getConnection("jdbc:h2:mem:empty" + System.nanoTime());
             Connection dst = DriverManager.getConnection("jdbc:h2:mem:dst2" + System.nanoTime())) {
            assertThat(H2ToPostgres.copyTable(src, dst, "candle")).isZero();
        }
    }
}
