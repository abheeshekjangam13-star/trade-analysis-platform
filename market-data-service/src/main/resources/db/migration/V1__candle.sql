-- Market data: OHLCV candles per symbol and interval (same shape as the earlier H2 table).
CREATE TABLE candle (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol        VARCHAR(20)                 NOT NULL,
    interval_code VARCHAR(10)                 NOT NULL,
    timestamp     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    open          NUMERIC(20, 8),
    high          NUMERIC(20, 8),
    low           NUMERIC(20, 8),
    close         NUMERIC(20, 8),
    volume        BIGINT                      NOT NULL,
    CONSTRAINT uk_candle_symbol_interval_ts UNIQUE (symbol, interval_code, timestamp)
);

CREATE INDEX idx_candle_symbol_interval ON candle (symbol, interval_code);
CREATE INDEX idx_candle_timestamp       ON candle (timestamp);
